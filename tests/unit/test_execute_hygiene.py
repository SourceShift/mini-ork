"""Execute harvest/argv hygiene (RBF-43, RB-03).

RB-43: ``__pycache__/*.pyc`` bytecode written by the verifier's own pytest run
is not an implementer change — it must not reach ``files_changed``, the
untracked harvest, or the resulting diff/diffstat. RB-03: a plan passed
positionally beats an inherited ``MINI_ORK_PLAN_PATH`` instead of becoming an
``Unexpected argument`` usage error.

Every git scenario is hermetic: a throwaway repo under ``tmp_path`` with no
``.gitignore`` (this repo's own ignore rules would hide bytecode and make the
test pass vacuously).
"""

import json
import os
import subprocess

import pytest

from mini_ork.cli.execute import (
    _append_untracked_hunks,
    _is_bytecode_path,
    _parse_execute_argv,
    _tree_has_no_change,
    _write_implementer_summary,
)

_GIT_COMMIT_CONFIG = (
    "-c", "user.email=test@example.invalid",
    "-c", "user.name=Execute Hygiene",
    "-c", "commit.gpgsign=false",
    "-c", "core.hooksPath=",
)


def _git(repo, *args):
    proc = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True)
    assert proc.returncode == 0, f"git {args} failed:\n{proc.stderr}"
    return proc.stdout


@pytest.fixture(autouse=True)
def _no_ambient_git(monkeypatch):
    """Keep GIT_* from the surrounding process out of the throwaway repos."""
    for var in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE",
                "GIT_CONFIG_GLOBAL", "GIT_CEILING_DIRECTORIES",
                "MINI_ORK_PLAN_PATH", "MINI_ORK_DRY_RUN"):
        monkeypatch.delenv(var, raising=False)


@pytest.fixture()
def git_repo(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q")
    (repo / "seed.txt").write_text("seed\n", encoding="utf-8")
    _git(repo, "add", "-A")
    _git(repo, *_GIT_COMMIT_CONFIG, "commit", "-q", "-m", "init")
    return repo


@pytest.fixture()
def run_dir(tmp_path):
    run = tmp_path / "run"
    run.mkdir()
    return run


def _summary(run_dir):
    with open(os.path.join(str(run_dir), "implementer-summary.json"),
              encoding="utf-8") as fh:
        return json.load(fh)


# --- RB-43: bytecode is not a change ---------------------------------------

def test_is_bytecode_path():
    assert _is_bytecode_path("pkg/__pycache__/m.cpython-313.pyc")
    assert _is_bytecode_path("top.pyc")
    assert _is_bytecode_path("compiled.pyo")
    assert _is_bytecode_path("pkg\\__pycache__\\m.pyc")
    assert not _is_bytecode_path("pkg/mod.py")
    assert not _is_bytecode_path("pkg/cache.pyc.txt")
    assert not _is_bytecode_path("pkg/__pycache__notes/mod.py")


def test_pyc_only_tree_is_not_implemented(git_repo, run_dir):
    pyc = git_repo / "pkg" / "__pycache__" / "m.cpython-313.pyc"
    pyc.parent.mkdir(parents=True)
    pyc.write_bytes(b"\x33\x0d\x0d\x0atest-run bytecode")

    returned = _write_implementer_summary(str(run_dir), str(git_repo), "impl log")

    payload = _summary(run_dir)
    assert payload["status"] != "implemented"
    assert payload["files_changed"] == []
    assert returned == []


def test_new_py_plus_pyc_lists_only_the_py(git_repo, run_dir):
    py = git_repo / "pkg" / "mod.py"
    py.parent.mkdir(parents=True)
    py.write_text("def f():\n    return 1\n", encoding="utf-8")
    cache = git_repo / "pkg" / "__pycache__"
    cache.mkdir()
    (cache / "mod.cpython-313.pyc").write_bytes(b"test-run bytecode")
    (git_repo / "top.pyc").write_bytes(b"test-run bytecode")
    (git_repo / "compiled.pyo").write_bytes(b"test-run bytecode")

    _write_implementer_summary(str(run_dir), str(git_repo), "impl log")

    files = _summary(run_dir)["files_changed"]
    assert files == [os.path.realpath(str(py))]
    assert not any("__pycache__" in f or f.endswith((".pyc", ".pyo"))
                   for f in files)


def test_tracked_modified_pyc_not_in_files_changed(git_repo, run_dir):
    pyc = git_repo / "legacy" / "__pycache__" / "old.cpython-313.pyc"
    pyc.parent.mkdir(parents=True)
    pyc.write_bytes(b"v1")
    app = git_repo / "app.py"
    app.write_text("print('v1')\n", encoding="utf-8")
    _git(git_repo, "add", "-A")
    _git(git_repo, *_GIT_COMMIT_CONFIG, "commit", "-q", "-m", "seed tracked files")

    pyc.write_bytes(b"v2 regenerated bytecode")
    app.write_text("print('v2')\n", encoding="utf-8")
    _write_implementer_summary(str(run_dir), str(git_repo), "impl log")

    files = _summary(run_dir)["files_changed"]
    assert os.path.realpath(str(app)) in files
    assert not any("__pycache__" in f or f.endswith((".pyc", ".pyo"))
                   for f in files)


def test_untracked_harvest_patch_excludes_bytecode(git_repo, run_dir):
    py = git_repo / "mod.py"
    py.write_text("x = 1\n", encoding="utf-8")
    cache = git_repo / "pkg" / "__pycache__"
    cache.mkdir(parents=True)
    (cache / "m.cpython-313.pyc").write_bytes(b"test-run bytecode")
    (git_repo / "top.pyc").write_bytes(b"test-run bytecode")
    (git_repo / "compiled.pyo").write_bytes(b"test-run bytecode")

    diff_path = run_dir / "review-diff.patch"
    _append_untracked_hunks(str(diff_path), str(git_repo), str(run_dir), [])

    patch = diff_path.read_text(encoding="utf-8", errors="replace")
    assert "+++ b/mod.py" in patch
    assert "__pycache__" not in patch
    assert ".pyc" not in patch
    assert ".pyo" not in patch
    assert patch.count("diff --git") == 1


def test_tree_has_no_change_ignores_bytecode(git_repo, run_dir):
    pyc = git_repo / "pkg" / "__pycache__" / "m.cpython-313.pyc"
    pyc.parent.mkdir(parents=True)
    pyc.write_bytes(b"test-run bytecode")

    assert _tree_has_no_change(str(git_repo), "HEAD", []) is True


# --- RB-03: a positional plan beats an inherited one -----------------------

def test_positional_plan_overrides_env_seeded_plan(monkeypatch):
    monkeypatch.setenv("MINI_ORK_PLAN_PATH", "/a/plan.json")

    args, rc = _parse_execute_argv(["/b/plan.json", "--recovery"])

    assert rc == 0
    assert args is not None
    assert args.plan_path == "/b/plan.json"
    assert args.recovery_active is True


def test_positional_override_prints_nothing(monkeypatch, capsys):
    monkeypatch.setenv("MINI_ORK_PLAN_PATH", "/a/plan.json")

    _parse_execute_argv(["/b/plan.json", "--recovery"])

    captured = capsys.readouterr()
    assert captured.out == ""
    assert captured.err == ""


def test_env_plan_still_used_without_positional(monkeypatch):
    monkeypatch.setenv("MINI_ORK_PLAN_PATH", "/a/plan.json")

    args, rc = _parse_execute_argv(["--recovery"])

    assert rc == 0
    assert args is not None
    assert args.plan_path == "/a/plan.json"


def test_two_positionals_are_still_an_error(monkeypatch, capsys):
    monkeypatch.setenv("MINI_ORK_PLAN_PATH", "/a/plan.json")

    args, rc = _parse_execute_argv(["/b/plan.json", "/c/plan.json"])
    assert (args, rc) == (None, 2)
    assert "Unexpected argument" in capsys.readouterr().err

    monkeypatch.delenv("MINI_ORK_PLAN_PATH", raising=False)
    args, rc = _parse_execute_argv(["/b/plan.json", "/c/plan.json"])
    assert (args, rc) == (None, 2)
